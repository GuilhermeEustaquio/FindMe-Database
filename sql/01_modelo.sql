CREATE TABLE fm_usuario (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (START WITH 100),
    nome VARCHAR2(100 CHAR) NOT NULL,
    email VARCHAR2(255 CHAR) NOT NULL,
    tipo_usuario VARCHAR2(15 CHAR) NOT NULL,
    data_cadastro TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
    CONSTRAINT fm_usuario_pk PRIMARY KEY (id),
    CONSTRAINT fm_usuario_email_uk UNIQUE (email),
    CONSTRAINT fm_usuario_tipo_ck CHECK (tipo_usuario IN ('RESPONSAVEL','COLABORADOR','MODERADOR'))
);

CREATE TABLE fm_caso (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (START WITH 100),
    responsavel_id NUMBER(19) NOT NULL,
    nome_desaparecido VARCHAR2(150 CHAR) NOT NULL,
    idade NUMBER(2) NOT NULL,
    descricao VARCHAR2(2000 CHAR) NOT NULL,
    ultima_localizacao_conhecida VARCHAR2(300 CHAR) NOT NULL,
    data_desaparecimento DATE NOT NULL,
    status VARCHAR2(20 CHAR) DEFAULT 'EM_ANALISE' NOT NULL,
    CONSTRAINT fm_caso_pk PRIMARY KEY (id),
    CONSTRAINT fm_caso_resp_fk FOREIGN KEY (responsavel_id) REFERENCES fm_usuario (id),
    CONSTRAINT fm_caso_idade_ck CHECK (idade BETWEEN 0 AND 17),
    CONSTRAINT fm_caso_status_ck CHECK (status IN
      ('EM_ANALISE','VALIDADO','PUBLICADO','EM_ACOMPANHAMENTO','LOCALIZADO','ENCERRADO'))
);

CREATE TABLE fm_alerta (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (START WITH 100),
    caso_id NUMBER(19) NOT NULL,
    titulo VARCHAR2(150 CHAR) NOT NULL,
    descricao_publica VARCHAR2(1000 CHAR) NOT NULL,
    data_publicacao TIMESTAMP NOT NULL,
    ativo NUMBER(1) NOT NULL,
    CONSTRAINT fm_alerta_pk PRIMARY KEY (id),
    CONSTRAINT fm_alerta_caso_uk UNIQUE (caso_id),
    CONSTRAINT fm_alerta_caso_fk FOREIGN KEY (caso_id) REFERENCES fm_caso (id),
    CONSTRAINT fm_alerta_ativo_ck CHECK (ativo IN (0,1))
);

CREATE TABLE fm_historico_status (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
    caso_id NUMBER(19) NOT NULL,
    autor_id NUMBER(19) NOT NULL,
    status_anterior VARCHAR2(20 CHAR),
    status_novo VARCHAR2(20 CHAR) NOT NULL,
    data_alteracao TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
    CONSTRAINT fm_hist_pk PRIMARY KEY (id),
    CONSTRAINT fm_hist_caso_fk FOREIGN KEY (caso_id) REFERENCES fm_caso (id),
    CONSTRAINT fm_hist_autor_fk FOREIGN KEY (autor_id) REFERENCES fm_usuario (id),
    CONSTRAINT fm_hist_novo_ck CHECK (status_novo IN
      ('EM_ANALISE','VALIDADO','PUBLICADO','EM_ACOMPANHAMENTO','LOCALIZADO','ENCERRADO')),
    CONSTRAINT fm_hist_ant_ck CHECK (status_anterior IN
      ('EM_ANALISE','VALIDADO','PUBLICADO','EM_ACOMPANHAMENTO','LOCALIZADO','ENCERRADO')),
    CONSTRAINT fm_hist_criacao_ck CHECK (
      (status_anterior IS NULL AND status_novo = 'EM_ANALISE') OR
      (status_anterior IS NOT NULL AND status_anterior <> status_novo))
);

CREATE INDEX fm_caso_resp_ix ON fm_caso (responsavel_id);
CREATE INDEX fm_hist_caso_ix ON fm_historico_status (caso_id, data_alteracao);
CREATE INDEX fm_hist_autor_ix ON fm_historico_status (autor_id);
